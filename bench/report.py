"""Summarise bench/results/*.csv into bench/results/summary.md and assets/headline.svg.

usage: python3 bench/report.py

Every number in the README comes from this script's output. Tiers:
  easy (seen)        test-a: PCBWorld's easy test split, identical to easy train, so it was
                     seen during development
  medium (held out)  sealed-b + the test-b boards not in dev-medium
  hard (held out)    sealed-c + the test-c boards not in dev-hard
  medium/hard (dev)  dev-medium / dev-hard: seen during development
Only boards present in both routers' CSVs are compared (paired). Rates carry Wilson 95%
intervals.
"""
import csv
import json
import math
import statistics
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
ROUTERS = ["copperline", "freerouting"]
# Boards that cannot be scored for one router through no fault of that router; dropped for
# both. KiCad 9's ImportSpecctraSES returns false on Freerouting's session file for 0498.
EXCLUDE = {"0498_kitspace_Spikeling_V2.1"}


def load(split, router):
    """Rows of one split/router, merged with any `--shard` CSVs of the same run."""
    out = {}
    base = f"{split}-{router}" if router else split
    for f in [RES / f"{base}.csv", *sorted(RES.glob(f"{base}-shard*.csv"))]:
        if f.exists():
            with open(f) as fh:
                out.update({r["board"]: r for r in csv.DictReader(fh)})
    return out


def capfmt(t):
    """Freerouting times at its time cap are the cap, not a measurement."""
    return f"{t:.0f} (cap)" if t >= 599 else f"{t:.1f}"


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def artifacts():
    """Boards whose KiCad errors are all DSN-conversion artifacts (bench/classify.py)."""
    f = RES / "violations.csv"
    if not f.exists():
        return {}
    by = {}
    for r in csv.DictReader(open(f)):
        by.setdefault((r["router"], r["board"]), set()).add(r["class"])
    return by


def forgiven_clean(r, router, art):
    """Clean, or fully connected with only conversion-artifact violations."""
    if r["clean"] == "1":
        return True
    if r["status"] != "ok" or r["unconnected"] not in ("0",):
        return False
    classes = art.get((router, r["board"]), set())
    return bool(classes) and classes <= {"text", "footprint", "rounding"}


def tiers():
    s = json.loads((HERE / "splits.json").read_text())
    dev_m, dev_h = set(s["dev-medium"]), set(s["dev-hard"])
    return [
        ("easy (seen in dev)", [("test-a", n) for n in s["test-a"]]),
        ("medium, held out", [("sealed-b", n) for n in s["sealed-b"]] + [("test-b", n) for n in s["test-b"] if n not in dev_m and n not in s["sealed-b"]]),
        ("hard, held out", [("sealed-c", n) for n in s["sealed-c"]] + [("test-c", n) for n in s["test-c"] if n not in dev_h and n not in s["sealed-c"]]),
    ]


def rows_for(members, router):
    cache = {}
    out = {}
    for split, name in members:
        key = (split, router)
        if key not in cache:
            cache[key] = load(split, router)
        if name in cache[key] and name not in EXCLUDE:
            out[name] = cache[key][name]
    return out


def secs(r):
    try:
        return float(r["route_s"])
    except (KeyError, ValueError):
        return None


def main():
    lines = ["# copperline vs Freerouting on PCBWorld D3, scored by KiCad 9 DRC", "",
             "Generated by `python3 bench/report.py` from `bench/results/*.csv`. Paired boards only.", "",
             "| tier | boards | copperline clean | Freerouting clean | Freerouting, conversion artifacts forgiven | copperline median / p90 s | Freerouting median / p90 s | both clean | only copperline | only Freerouting |",
             "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    art = artifacts()
    per_board = ["| tier | board | copperline | Freerouting | copperline s | Freerouting s |", "|---|---|---|---|---:|---:|"]
    chart = []
    tier_stats = {}
    for name, members in tiers():
        a = rows_for(members, "copperline")
        b = rows_for(members, "freerouting")
        common = sorted(set(a) & set(b))
        n = len(common)
        if n == 0:
            lines.append(f"| {name} | 0 | | | | | | | | |")
            continue
        ka = sum(int(a[x]["clean"]) for x in common)
        kb = sum(int(b[x]["clean"]) for x in common)
        both = sum(int(a[x]["clean"]) and int(b[x]["clean"]) for x in common)
        ta = sorted(t for t in (secs(a[x]) for x in common) if t is not None)
        tb = sorted(t for t in (secs(b[x]) for x in common) if t is not None)
        q = lambda t, f: t[min(len(t) - 1, int(f * len(t)))]
        wa, wb = wilson(ka, n), wilson(kb, n)
        kf = sum(forgiven_clean(b[x], "freerouting", art) for x in common)
        wf = wilson(kf, n)
        # The idle rerun overwrote the medium boards' Freerouting outputs that the error
        # classification reads, so that cell belongs to the head-to-head table only.
        fcell = "see head-to-head" if name == "medium, held out" and load("sealed-b", "freerouting-idle") else f"{kf}/{n} = {kf / n:.2f} [{wf[0]:.2f}, {wf[1]:.2f}]"
        verdict = lambda r: "clean" if r["clean"] == "1" else (r["status"] if r["status"] != "ok" else ", ".join(
            filter(None, [f"{r['unconnected']} unconnected" if r["unconnected"] not in ("", "0") else "",
                          f"{r['violation_types']}" if r["violations"] not in ("", "0") else ""])))
        for x in common:
            per_board.append(f"| {name} | {x} | {verdict(a[x])} | {verdict(b[x])} | {a[x]['route_s']} | {b[x]['route_s']} |")
        lines.append(
            f"| {name} | {n} | {ka}/{n} = {ka / n:.2f} [{wa[0]:.2f}, {wa[1]:.2f}] | {kb}/{n} = {kb / n:.2f} [{wb[0]:.2f}, {wb[1]:.2f}] | {fcell} | "
            f"{statistics.median(ta):.1f} / {q(ta, 0.9):.1f} | {capfmt(statistics.median(tb))} / {capfmt(q(tb, 0.9))} | {both} | {ka - both} | {kb - both} |")
        chart.append((name, n, ka / n, wa, kb / n, wb, statistics.median(ta), statistics.median(tb)))
        tier_stats[name] = dict(n=n, ka=ka, kb=kb, kf=kf, ma=statistics.median(ta), mb=statistics.median(tb))
    lines += ["", "## copperline on every board of each tier (not only those Freerouting finished)", "",
              "| tier | boards routed | clean | boards where KiCad found errors in copperline's copper |", "|---|---:|---:|---:|"]
    for name, members in tiers():
        a = rows_for(members, "copperline")
        if not a:
            continue
        k = sum(int(r["clean"]) for r in a.values())
        v = sum(1 for r in a.values() if r["violations"] not in ("", "0"))
        w = wilson(k, len(a))
        lines.append(f"| {name} | {len(a)} | {k}/{len(a)} = {k / len(a):.2f} [{w[0]:.2f}, {w[1]:.2f}] | {v} |")
    # DRC agreement: copperline never writes copper that fails its own DRC, so every KiCad
    # error on its output is a miss of copperline's checker.
    allrows = {}
    for f in RES.glob("*-copperline*.csv"):
        for r in csv.DictReader(open(f)):
            allrows[(f.name, r["board"])] = r
    routed = [r for r in allrows.values() if r["status"] == "ok"]
    missed = [r for r in routed if r["violations"] not in ("", "0")]
    lines += ["", f"copperline's own DRC vs KiCad: KiCad found errors in copperline's copper on {len(missed)} of {len(routed)} routed board runs "
              f"({', '.join(sorted({r['board'] for r in missed})) or 'none'}).", ""]
    # Parity with PCBWorld's published Freerouting numbers (RQ2, d3a fair-95): mean DRV over
    # fully routed boards 0.09, routability 0.98.
    fr = load("test-a", "freerouting")
    full = [r for r in fr.values() if r["status"] == "ok" and r["unconnected"] == "0"]
    drv = statistics.mean(int(r["violations"] or 0) for r in full) if full else float("nan")
    # Routability as PCBWorld defines it: per board, the fraction of connections routed,
    # averaged over all boards. Connection counts come from copperline's stats for the same
    # input; KiCad's unconnected items count the missing ones; timeouts and errors count 0.
    fracs = []
    for name, r in fr.items():
        sj = HERE / "work" / "copperline" / name / "routed.stats.json"
        if not sj.exists():
            continue
        conns = json.loads(sj.read_text()).get("connections", 0)
        if conns == 0:
            continue
        if r["status"] != "ok":
            fracs.append(0.0)
        else:
            fracs.append(max(0.0, 1 - int(r["unconnected"] or 0) / conns))
    rout = statistics.mean(fracs) if fracs else float("nan")
    lines += ["## Parity with PCBWorld's published Freerouting run (D3-A)", "",
              "PCBWorld (RQ2 table, d3a fair-95 subset, Freerouting 2.1.0, mean of 4 seeds) reports mean DRC violations 0.09 on fully routed boards and routability 0.98 (mean fraction of nets routed). Clean-pass is not published, so this compares what can be compared:", "",
              f"- our single-seed run on test-a: routability {rout:.2f} (PCBWorld: 0.98), mean DRC violations on fully routed boards {drv:.2f} (PCBWorld: 0.09; ours includes the DSN-conversion artifacts above), {len(full)}/{len(fr)} boards fully routed",
              f"- clean-pass of our run: {sum(int(r['clean']) for r in fr.values())}/{len(fr)}", ""]
    # Main result: the current, deterministic build (effort budget, no wall clock in the
    # loop) against Freerouting run one board at a time on an otherwise idle machine.
    lead = ["## Head to head, one board at a time (current build)", "",
            "| tier | boards | copperline clean | Freerouting clean | Freerouting, conversion artifacts forgiven | copperline median / p90 s | Freerouting median / p90 s | both clean | only copperline | only Freerouting |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    idle = {}
    a = {k: v for k, v in load("sealed-b", "copperline-det").items() if k not in EXCLUDE}
    b = {k: v for k, v in load("sealed-b", "freerouting-idle").items() if k not in EXCLUDE}
    common = sorted(set(a) & set(b))
    if common:
        n = len(common)
        ka = sum(int(a[x]["clean"]) for x in common)
        kb = sum(int(b[x]["clean"]) for x in common)
        kf = sum(forgiven_clean(b[x], "freerouting", art) for x in common)
        both = sum(int(a[x]["clean"]) and int(b[x]["clean"]) for x in common)
        ta = sorted(float(a[x]["route_s"] or 0) for x in common)
        tb = sorted(float(b[x]["route_s"] or 0) for x in common)
        q = lambda t, f: t[min(len(t) - 1, int(f * len(t)))]
        wa, wb, wf = wilson(ka, n), wilson(kb, n), wilson(kf, n)
        lead.append(f"| medium, held out | {n} | {ka}/{n} = {ka / n:.2f} [{wa[0]:.2f}, {wa[1]:.2f}] | {kb}/{n} = {kb / n:.2f} [{wb[0]:.2f}, {wb[1]:.2f}] | "
                    f"{kf}/{n} = {kf / n:.2f} [{wf[0]:.2f}, {wf[1]:.2f}] | {statistics.median(ta):.1f} / {q(ta, 0.9):.1f} | "
                    f"{capfmt(statistics.median(tb))} / {capfmt(q(tb, 0.9))} | {both} | {ka - both} | {kb - both} |")
        idle["medium"] = dict(n=n, ka=ka, kb=kb, kf=kf, ma=statistics.median(ta), mb=statistics.median(tb), wa=wa, wb=wb)
    h1 = {k: v for k, v in load("sealed-c", "copperline-det").items() if k not in EXCLUDE}
    h2 = {k: v for k, v in load("sealed-c", "copperline-det2").items() if k not in EXCLUDE}
    h = h2 or h1
    # Reproducibility: the deterministic build routed sealed-c twice (two builds whose
    # routing code is identical, run with different machine load); compare board by board.
    same = [x for x in set(h1) & set(h2) if (h1[x]["clean"], h1[x]["unconnected"], h1[x]["tracks"], h1[x]["vias"]) == (h2[x]["clean"], h2[x]["unconnected"], h2[x]["tracks"], h2[x]["vias"])]
    repro = f"Run twice, the hard-tier result was identical (clean, unconnected, track and via counts) on {len(same)} of {len(set(h1) & set(h2))} boards." if h1 and h2 else ""
    if h:
        k = sum(int(r["clean"]) for r in h.values())
        t = sorted(float(r["route_s"] or 0) for r in h.values())
        w = wilson(k, len(h))
        builds = sorted({r.get("commit", "") for r in list(a.values()) + list(h.values())})
        lead += ["", "| copperline alone | boards | clean | median / p90 / max s |", "|---|---:|---:|---:|",
                 f"| hard, held out | {len(h)} | {k}/{len(h)} = {k / len(h):.2f} [{w[0]:.2f}, {w[1]:.2f}] | {statistics.median(t):.1f} / {t[int(0.9 * len(t))]:.1f} / {t[-1]:.0f} |",
                 "", f"copperline build for these rows: {', '.join(builds)}, default effort budget. {repro}"]
        idle["hard"] = dict(n=len(h), k=k, m=statistics.median(t), w=w)
    lines[4:4] = lead + ["", "## Earlier run: frozen build, both routers sharing a loaded laptop", ""]
    cur = idle
    readme_blocks(lines, tier_stats, missed, routed, cur)
    if idle:
        chart = [("medium, held out", idle["medium"]["n"], idle["medium"]["ka"] / idle["medium"]["n"], idle["medium"]["wa"],
                  idle["medium"]["kb"] / idle["medium"]["n"], idle["medium"]["wb"], idle["medium"]["ma"], idle["medium"]["mb"])] if "medium" in idle else []
        if "hard" in idle:
            hd = idle["hard"]
            chart.append(("hard, held out", hd["n"], hd["k"] / hd["n"], hd["w"], None, None, hd["m"], None))
    # Failure classes.
    lines += ["", "## Why boards are not clean (paired boards)", "", "| router | tier | unconnected only | DRC violations | timeout / error |", "|---|---|---:|---:|---:|"]
    for name, members in tiers():
        both = set(rows_for(members, "copperline")) & set(rows_for(members, "freerouting"))
        for router in ROUTERS:
            rs = {k: v for k, v in rows_for(members, router).items() if k in both}
            bad = [r for r in rs.values() if r["clean"] != "1"]
            unc = sum(1 for r in bad if r["status"] == "ok" and r["violations"] in ("0", ""))
            vio = sum(1 for r in bad if r["status"] == "ok" and r["violations"] not in ("0", ""))
            err = sum(1 for r in bad if r["status"] != "ok")
            lines.append(f"| {router} | {name} | {unc} | {vio} | {err} |")
    # Violation types.
    types = {}
    for name, members in tiers():
        both = set(rows_for(members, "copperline")) & set(rows_for(members, "freerouting"))
        for router in ROUTERS:
            for k, r in rows_for(members, router).items():
                if k not in both:
                    continue
                for part in filter(None, r.get("violation_types", "").split(";")):
                    t, k = part.split(":")
                    types[(router, t)] = types.get((router, t), 0) + int(k)
    if types:
        lines += ["", "## DRC violation types (paired boards, all tiers)", "", "| router | type | count |", "|---|---|---:|"]
        for (router, t), k in sorted(types.items()):
            lines.append(f"| {router} | {t} | {k} |")
    # Development pools.
    s = json.loads((HERE / "splits.json").read_text())
    lines += ["", "## Development pools (copperline only, seen during development; dev-medium was run with a pre-freeze version)", "", "| pool | boards | clean | median / p90 s |", "|---|---:|---:|---:|"]
    for split in ["dev-easy", "dev-medium", "dev-hard"]:
        # dev-easy-copperline-v2.csv is the regression run of the frozen version.
        rs = load(split + "-copperline-v2", "") if (RES / f"{split}-copperline-v2.csv").exists() else load(split, "copperline")
        if not rs:
            continue
        k = sum(int(r["clean"]) for r in rs.values())
        t = sorted(x for x in (secs(r) for r in rs.values()) if x is not None)
        lines.append(f"| {split} | {len(rs)} | {k}/{len(rs)} = {k / len(rs):.2f} | {statistics.median(t):.1f} / {t[int(0.9 * len(t))]:.1f} |")
    (RES / "summary.md").write_text("\n".join(lines) + "\n")
    (RES / "per-board.md").write_text("# Per-board results (paired boards)\n\nGenerated by bench/report.py.\n\n" + "\n".join(per_board) + "\n")
    print("\n".join(lines))
    if chart:
        write_chart(chart)


def readme_blocks(lines, ts, missed, routed, cur=None):
    """Write the headline and the results tables into README.md between markers."""
    readme = HERE.parent / "README.md"
    if not readme.exists():
        return
    text = readme.read_text()
    m, h = ts.get("medium, held out"), ts.get("hard, held out")
    if not (m and h):
        return
    allc = {}
    for name, members in tiers():
        allc[name] = rows_for(members, "copperline")
    hard_all = allc["hard, held out"]
    hk = sum(int(r["clean"]) for r in hard_all.values())
    slow = max(float(r["route_s"] or 0) for name in ("medium, held out", "hard, held out") for r in allc[name].values())
    fr_hard = rows_for(dict(tiers())["hard, held out"], "freerouting")
    timeouts = sum(1 for r in fr_hard.values() if r["status"] == "timeout")
    md, hd = (cur or {}).get("medium"), (cur or {}).get("hard")
    if md and hd:
        headline = (f"On {md['n']} real open-hardware boards of medium size that it never saw during development, routed one at a time "
                    f"with the same input files and scored by KiCad 9's own DRC, copperline produces **{md['ka'] / md['n']:.0%} clean boards against "
                    f"Freerouting's {md['kb'] / md['n']:.0%}** ({md['kf'] / md['n']:.0%} if Freerouting is forgiven the errors KiCad's DSN export "
                    f"causes), with a median of {md['ma']:.1f} s per board against {md['mb']:.0f} s. On {hd['n']} hard boards it routes "
                    f"{hd['k'] / hd['n']:.0%} clean (median {hd['m']:.0f} s) with a deterministic effort budget.")
    else:
        headline = "(results pending)"
    start, end = "<!-- headline:start -->", "<!-- headline:end -->"
    if start in text:
        text = text[: text.index(start) + len(start)] + "\n" + headline + "\n" + text[text.index(end):]
    body = "\n".join(lines[lines.index("## Head to head, one board at a time (current build)"):])
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    held = [r for name in ("medium, held out", "hard, held out") for r in allc[name].values()]
    capped = [r["board"] for r in held if r["status"] == "timeout"]
    rest = max(float(r["route_s"] or 0) for r in held if r["status"] != "timeout")
    extra = (f"\n\nThe slowest completed held-out copperline run took {rest:.0f} s"
             + (f"; the frozen build ran into the bench's 1800 s cap on {', '.join(capped)}, because its time budget was "
                "only checked between negotiation passes (it is a deadline since; see Limitations)." if capped else "."))
    if len(hard_all) != h["n"]:
        extra += (f" Hard tier, all {len(hard_all)} boards copperline routed (including those Freerouting has no result for): "
                  f"{hk}/{len(hard_all)} = {hk / len(hard_all):.2f} clean.")
    if start in text:
        text = text[: text.index(start) + len(start)] + "\n" + body.replace("## ", "#### ") + extra + "\n" + text[text.index(end):]
    readme.write_text(text)


def write_chart(chart):
    W, H = 760, 350
    left, top, bw = 70, 84, 46
    gw = (W - left - 40) / len(chart)
    ph = 190
    y = lambda v: top + ph * (1 - v)
    col = {"copperline": "#d9822b", "freerouting": "#6b7c93"}
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="Helvetica, Arial, sans-serif">',
         f'<rect width="{W}" height="{H}" fill="#ffffff"/>',
         f'<text x="{left}" y="28" font-size="17" font-weight="bold" fill="#1d2733">Boards routed with zero KiCad 9 DRC errors (clean-pass)</text>',
         f'<text x="{left}" y="47" font-size="12" fill="#56606e">Held-out PCBWorld D3 boards, one board at a time, same input files; whiskers: Wilson 95% intervals</text>']
    for v in [0, 0.25, 0.5, 0.75, 1.0]:
        o.append(f'<line x1="{left}" x2="{W - 30}" y1="{y(v):.1f}" y2="{y(v):.1f}" stroke="#e3e7ec"/>')
        o.append(f'<text x="{left - 8}" y="{y(v) + 4:.1f}" font-size="11" text-anchor="end" fill="#56606e">{v:.2f}</text>')
    for i, (name, n, pa, wa, pb, wb, ma, mb) in enumerate(chart):
        gx = left + i * gw + gw / 2
        for j, (router, pv, wv, med) in enumerate([("copperline", pa, wa, ma), ("freerouting", pb, wb, mb)]):
            if pv is None:
                cx = gx - bw - 4 + j * (bw + 8) + bw / 2
                o.append(f'<text x="{cx:.1f}" y="{top + ph - 8:.1f}" font-size="10" text-anchor="middle" fill="#56606e">not rerun</text>')
                continue
            x = gx - bw - 4 + j * (bw + 8)
            o.append(f'<rect x="{x:.1f}" y="{y(pv):.1f}" width="{bw}" height="{ph * pv:.1f}" fill="{col[router]}"/>')
            cx = x + bw / 2
            o.append(f'<line x1="{cx:.1f}" x2="{cx:.1f}" y1="{y(wv[0]):.1f}" y2="{y(wv[1]):.1f}" stroke="#1d2733" stroke-width="1.2"/>')
            o.append(f'<text x="{cx:.1f}" y="{y(wv[1]) - 6:.1f}" font-size="12" text-anchor="middle" fill="#1d2733" font-weight="bold">{pv:.2f}</text>')
            o.append(f'<text x="{cx:.1f}" y="{top + ph + 16:.1f}" font-size="10.5" text-anchor="middle" fill="#56606e">{f"{med:.0f} s (cap)" if med >= 599 else f"{med:.1f} s"}</text>')
        o.append(f'<text x="{gx:.1f}" y="{top + ph + 34:.1f}" font-size="12.5" text-anchor="middle" fill="#1d2733">{name}</text>')
        o.append(f'<text x="{gx:.1f}" y="{top + ph + 50:.1f}" font-size="11" text-anchor="middle" fill="#56606e">n = {n}</text>')
    lx = left
    for router, label in [("copperline", "copperline"), ("freerouting", "Freerouting 2.1.0")]:
        o.append(f'<rect x="{lx}" y="{H - 24}" width="12" height="12" fill="{col[router]}"/>')
        o.append(f'<text x="{lx + 17}" y="{H - 14}" font-size="12" fill="#1d2733">{label}</text>')
        lx += 150
    o.append(f'<text x="{W - 30}" y="{H - 14}" font-size="11" text-anchor="end" fill="#56606e">numbers under bars: median route time per board</text>')
    o.append("</svg>")
    (HERE.parent / "assets").mkdir(exist_ok=True)
    (HERE.parent / "assets" / "headline.svg").write_text("\n".join(o) + "\n")


